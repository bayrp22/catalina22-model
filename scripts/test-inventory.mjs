import assert from 'node:assert/strict';
import {newInventory,validateInventory,rows,findRecord,editRecord} from '../dist/inventory-data.js';
const empty=newInventory();assert.equal(rows(validateInventory(empty)).length,0);
const base=newInventory();
base.catalog.push({id:'NAV-001',name:'Generic test device',modelPlacement:{positionMeters:null,parentPartId:null}});
base.placementProposals.push({id:'PROPOSED-GALLEY',label:'Test galley',positionMeters:null});
const checked=validateInventory(base);
assert.equal(rows(checked).length,2);
assert.equal(findRecord(checked,'NAV-001').entry.name,'Generic test device');
const updated=editRecord(checked,'NAV-001',(_entry,placement)=>{placement.positionMeters=[-1.2,0.65,-.5];placement.reviewed=false;});
assert.deepEqual(findRecord(updated,'NAV-001').placement.positionMeters,[-1.2,.65,-.5]);
assert.equal(findRecord(checked,'NAV-001').placement.positionMeters,null,'Original input must remain unchanged');
assert.throws(()=>validateInventory({...base,format:'other'}),/Not a Catalina/);
assert.throws(()=>validateInventory({...base,catalog:[...base.catalog,{id:'NAV-001',name:'Duplicate'}]}),/Duplicate/);
assert.throws(()=>validateInventory({...base,catalog:[{id:'BAD/NAME',name:'Invalid'}]}),/Invalid/);
assert.throws(()=>validateInventory({...base,catalog:[{id:'NAV-001',name:'Bad coordinates',modelPlacement:{positionMeters:[NaN,0,0]}}]}),/Invalid coordinates/);
assert.throws(()=>validateInventory({...base,catalog:[{id:'NAV-001',name:'Bad coordinates',modelPlacement:{positionMeters:[1,2]}}]}),/Invalid coordinates/);
assert.deepEqual(validateInventory(JSON.parse(JSON.stringify(updated))),updated,'Private JSON must survive import/export roundtrip');
console.log('Inventory schema tests passed (private data never bundled).');
